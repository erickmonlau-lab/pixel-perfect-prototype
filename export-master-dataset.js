function exportToCsv(filename, data) {
  if (!data || !data.length) return;
  const headers = Object.keys(data[0]);
  const rows = data.map(obj => headers.map(h => {
    let val = obj[h] === undefined || obj[h] === null ? '' : String(obj[h]);
    val = val.replace(/\"/g, '\"\"');
    return `\"${val}\"`;
  }).join(','));
  const csvContent = [headers.join(','), ...rows].join('\n');
  
  const p1 = path.join('C:/Users/erick/.gemini/antigravity/scratch/arvio', filename);
  const p2 = path.join('C:/Users/erick/.gemini/antigravity/brain/0d16c14d-6226-4731-922f-88db82a8c520', filename);
  fs.writeFileSync(p1, csvContent, 'utf8');
  fs.writeFileSync(p2, csvContent, 'utf8');
  console.log(`Saved ${filename} to scratch and brain.`);
}

